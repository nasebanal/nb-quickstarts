#!/bin/sh
# `docker compose` for the apps stack, with as many backend instances as
# APPS_BACKEND_INSTANCES asks for (default 1 - just apps' own `backend`).
#
#   sh apps/bin/compose.sh up -d --build
#   APPS_BACKEND_INSTANCES=3 sh apps/bin/compose.sh up -d --build
#
# apps' `backend` is always instance 1 (published on 8080); backend-2 ..
# backend-N are added by a compose file generated here for the N asked for -
# each `extends` apps' own backend service, so it has the same image, code,
# environment and database, and follows apps/docker-compose.yml. Only `up`
# regenerates the file (going to a smaller N drops the surplus containers,
# `--remove-orphans`); every other command (down, ps, logs, ...) just uses the
# file that is there.
set -e

HERE=$(cd "$(dirname "$0")/.." && pwd)
BASE="$HERE/docker-compose.yml"
OVERLAY="$HERE/.backends.generated.yml"
N=${APPS_BACKEND_INSTANCES:-1}

generate() {
	{
		echo "# Generated by apps/bin/compose.sh for APPS_BACKEND_INSTANCES=$N - do not edit."
		echo "services:"
		i=2
		while [ "$i" -le "$N" ]; do
			cat <<YAML
  backend-$i:
    extends:
      file: docker-compose.yml
      service: backend
    container_name: nb-backend-$i
    # The image is the one \`backend\` builds; only instance 1 publishes 8080.
    build: !reset null
    ports: !reset []
    environment:
      INSTANCE_ID: backend-$i
YAML
			i=$((i + 1))
		done
	} >"$OVERLAY"
}

if [ "$1" = "up" ]; then
	if [ "$N" -lt 1 ] 2>/dev/null; then
		echo "APPS_BACKEND_INSTANCES must be 1 or more (it counts apps' own backend)" >&2
		exit 1
	fi
	if [ "$N" -ge 2 ]; then generate; else rm -f "$OVERLAY"; fi
	set -- "$@" --remove-orphans
fi

if [ -f "$OVERLAY" ]; then
	exec docker compose -p apps -f "$BASE" -f "$OVERLAY" "$@"
fi
exec docker compose -p apps -f "$BASE" "$@"
